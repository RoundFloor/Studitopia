CREATE OR REPLACE FUNCTION STUDITOPIA.GET_COMMENT(P_POST_ID INT)
RETURNS TABLE(ID INT, CONTENT TEXT, ACCOUNT_ID INT, UPVOTE INT, DOWNVOTE INT, NUM_COMMENT INT, CREATED_TIME TIMESTAMPTZ)
AS $$
    WITH RECURSIVE THREAD AS (
        SELECT C.ID
        FROM STUDITOPIA.POST P
        JOIN STUDITOPIA.COMMENT C ON C.ID = P.COMMENT_ID
        WHERE P.ID = P_POST_ID
        UNION ALL
        SELECT C.ID
        FROM STUDITOPIA.COMMENT C
        JOIN THREAD T ON C.COMMENT_ID = T.ID
    )
    SELECT C.ID, C.CONTENT, C.ACCOUNT_ID, C.UPVOTE, C.DOWNVOTE, C.COMMENT, C.CREATED_TIME
    FROM THREAD T
    JOIN STUDITOPIA.COMMENT C ON C.ID = T.ID
    ORDER BY C.CREATED_TIME, C.ID;
$$ LANGUAGE SQL;

CREATE OR REPLACE FUNCTION STUDITOPIA.GET_COMMENT_OF_COMMENT(P_COMMENT_ID INT)
RETURNS TABLE(ID INT, CONTENT TEXT, ACCOUNT_ID INT, UPVOTE INT, DOWNVOTE INT, NUM_COMMENT INT, CREATED_TIME TIMESTAMPTZ)
AS $$
    SELECT C.ID, C.CONTENT, C.ACCOUNT_ID, C.UPVOTE, C.DOWNVOTE, C.COMMENT, C.CREATED_TIME
    FROM STUDITOPIA.COMMENT C
    WHERE C.COMMENT_ID = P_COMMENT_ID
    ORDER BY C.CREATED_TIME, C.ID;
$$ LANGUAGE SQL;
