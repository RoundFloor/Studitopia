DROP FUNCTION IF EXISTS STUDITOPIA.GET_SUBJECT(INT);
CREATE OR REPLACE FUNCTION STUDITOPIA.GET_SUBJECT(P_AREA_ID INT)
RETURNS TABLE (ID INT, NAME TEXT, NUM_TAG INT, NUM_POST INT, ICON INT, DESCRIPTION TEXT)
AS $$
    SELECT DISTINCT T.ID, T.NAME, T.NUM_TAG, T.NUM_POST, T.ICON, T.DESCRIPTION
    FROM STUDITOPIA.GET_TAG('SUBJECT') T
    JOIN STUDITOPIA.TAG_CONTAIN TC ON TC.TAG_ID_A = P_AREA_ID AND TC.TAG_ID_B = T.ID
    ORDER BY T.NAME, T.ID;
$$ LANGUAGE SQL;
