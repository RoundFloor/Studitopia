DROP FUNCTION IF EXISTS STUDITOPIA.GET_POST(INT[]);
DROP FUNCTION IF EXISTS STUDITOPIA.GET_POST(INT[], INT[]);

CREATE OR REPLACE FUNCTION STUDITOPIA.GET_POST(P_INCLUDED_TAGS INT[], P_EXCLUDED_TAGS INT[])
RETURNS TABLE (ID INT, TITLE TEXT, ACCOUNT_ID INT, DISPLAYNAME VARCHAR(32), AVATAR_ID INT, COMMENT_ID INT, CONTENT TEXT, UPVOTE INT, DOWNVOTE INT, NUM_COMMENT INT, TRUE_RESPONSE INT, CREATED_TIME TIMESTAMPTZ, TAGS INT[])
AS $$
    SELECT (STUDITOPIA.GET_POST_BY_ID(P.ID)).*
    FROM STUDITOPIA.POST P
    WHERE (
        P_INCLUDED_TAGS IS NULL
        OR CARDINALITY(P_INCLUDED_TAGS) = 0
        OR P.ID IN (
            SELECT IPT.POST_ID
            FROM STUDITOPIA.INCLUDE_POST_TAG IPT
            WHERE IPT.TAG_ID = ANY(P_INCLUDED_TAGS)
            GROUP BY IPT.POST_ID
            HAVING COUNT(DISTINCT IPT.TAG_ID) = CARDINALITY(P_INCLUDED_TAGS)
        )
    )
    AND (
        P_EXCLUDED_TAGS IS NULL
        OR CARDINALITY(P_EXCLUDED_TAGS) = 0
        OR NOT EXISTS (
            SELECT 1
            FROM STUDITOPIA.INCLUDE_POST_TAG IPT
            WHERE IPT.POST_ID = P.ID
              AND IPT.TAG_ID = ANY(P_EXCLUDED_TAGS)
        )
    )
    ORDER BY P.ID;
$$ LANGUAGE SQL;