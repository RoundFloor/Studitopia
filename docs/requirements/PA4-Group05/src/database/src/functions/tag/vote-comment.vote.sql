CREATE OR REPLACE FUNCTION STUDITOPIA.VOTE_COMMENT(P_COMMENT_ID INT, P_ACCOUNT_ID INT, P_TYPE INT DEFAULT 0)
RETURNS INT AS $$
DECLARE
    V_VOTE_ID INT;
BEGIN
    IF P_TYPE IS NULL OR P_TYPE NOT IN (0, 1) THEN
        RAISE EXCEPTION 'Invalid vote type' USING ERRCODE = '23514';
    END IF;

    INSERT INTO STUDITOPIA.VOTE(COMMENT_ID, ACCOUNT_ID, TYPE)
    VALUES (P_COMMENT_ID, P_ACCOUNT_ID, P_TYPE)
    ON CONFLICT (COMMENT_ID, ACCOUNT_ID)
    DO UPDATE SET TYPE = EXCLUDED.TYPE, TIME_CREATED = NOW()
    RETURNING ID INTO V_VOTE_ID;

    RETURN V_VOTE_ID;
END $$ LANGUAGE plpgsql;
