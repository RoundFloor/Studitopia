DROP FUNCTION IF EXISTS STUDITOPIA.CREATE_COMMENT(INT, INT, TEXT, INT);

CREATE OR REPLACE FUNCTION STUDITOPIA.CREATE_COMMENT(P_PARENT_COMMENT_ID INT, P_CONTENT TEXT, P_ACCOUNT_ID INT)
RETURNS INT AS $$
    INSERT INTO STUDITOPIA.COMMENT(CONTENT, ACCOUNT_ID, COMMENT_ID)
    VALUES (P_CONTENT, P_ACCOUNT_ID, P_PARENT_COMMENT_ID)
    RETURNING ID;
$$ LANGUAGE SQL;
