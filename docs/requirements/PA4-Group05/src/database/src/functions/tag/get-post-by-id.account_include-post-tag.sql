DROP FUNCTION IF EXISTS STUDITOPIA.GET_POST_BY_ID(INT);

CREATE OR REPLACE FUNCTION STUDITOPIA.GET_POST_BY_ID(P_POST_ID INT)
RETURNS TABLE (ID INT, TITLE TEXT, ACCOUNT_ID INT, DISPLAYNAME VARCHAR(32), AVATAR_ID INT, COMMENT_ID INT, CONTENT TEXT, UPVOTE INT, DOWNVOTE INT, NUM_COMMENT INT, TRUE_RESPONSE INT, CREATED_TIME TIMESTAMPTZ, TAGS INT[])
AS $$
    SELECT P.ID, P.TITLE, P.ACCOUNT_ID, A.DISPLAYNAME, A.AVATAR, P.COMMENT_ID, C.CONTENT, C.UPVOTE, C.DOWNVOTE, C.COMMENT, P.TRUE_RESPONSE, P.CREATED_TIME,
           COALESCE(ARRAY_AGG(IPT.TAG_ID ORDER BY IPT.TAG_ID) FILTER (WHERE IPT.TAG_ID IS NOT NULL), '{}'::INT[])
    FROM STUDITOPIA.POST P
    JOIN STUDITOPIA.ACCOUNT A ON A.ID = P.ACCOUNT_ID
    JOIN STUDITOPIA.COMMENT C ON C.ID = P.COMMENT_ID
    LEFT JOIN STUDITOPIA.INCLUDE_POST_TAG IPT ON IPT.POST_ID = P.ID
    WHERE P.ID = P_POST_ID
    GROUP BY P.ID, P.TITLE, P.ACCOUNT_ID, A.DISPLAYNAME, A.AVATAR, P.COMMENT_ID, P.TRUE_RESPONSE, P.CREATED_TIME, C.CONTENT, C.UPVOTE, C.DOWNVOTE, C.COMMENT;
$$ LANGUAGE SQL;
