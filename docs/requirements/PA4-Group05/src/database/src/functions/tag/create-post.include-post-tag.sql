DROP FUNCTION IF EXISTS STUDITOPIA.CREATE_POST(TEXT, TEXT, INT);

CREATE OR REPLACE FUNCTION STUDITOPIA.CREATE_POST(P_TITLE TEXT, P_CONTENT TEXT, P_ACCOUNT_ID INT, P_TAGS INT[])
RETURNS INT AS $$
DECLARE
    V_COMMENT_ID INT;
    V_POST_ID INT;
BEGIN
    INSERT INTO STUDITOPIA.COMMENT(CONTENT, ACCOUNT_ID)
    VALUES (P_CONTENT, P_ACCOUNT_ID)
    RETURNING ID INTO V_COMMENT_ID;

    INSERT INTO STUDITOPIA.POST(TITLE, ACCOUNT_ID, COMMENT_ID)
    VALUES (P_TITLE, P_ACCOUNT_ID, V_COMMENT_ID)
    RETURNING ID INTO V_POST_ID;

    IF P_TAGS IS NOT NULL THEN
        INSERT INTO STUDITOPIA.INCLUDE_POST_TAG(POST_ID, TAG_ID)
        SELECT V_POST_ID, T.TAG_ID
        FROM (SELECT DISTINCT UNNEST(P_TAGS) AS TAG_ID) T;
    END IF;

    RETURN V_POST_ID;
END $$ LANGUAGE plpgsql;
