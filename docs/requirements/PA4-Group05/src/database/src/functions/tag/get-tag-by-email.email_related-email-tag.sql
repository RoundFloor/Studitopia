DROP FUNCTION IF EXISTS STUDITOPIA.GET_TAG_BY_EMAIL(STUDITOPIA.TYPE_EMAIL);
CREATE OR REPLACE FUNCTION STUDITOPIA.GET_TAG_BY_EMAIL(P_EMAIL STUDITOPIA.TYPE_EMAIL)
RETURNS TABLE (ID INT, NAME TEXT, NUM_TAG INT, NUM_POST INT, ICON INT, DESCRIPTION TEXT)
AS $$
    SELECT T.ID, T.NAME, T.NUM_TAG, T.NUM_POST, T.ICON, T.DESCRIPTION
    FROM STUDITOPIA.DOMAIN D
    JOIN STUDITOPIA.RELATED_EMAIL_TAG RET ON RET.DOMAIN_ID = D.ID
    JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
    WHERE D.DOMAIN = SPLIT_PART(P_EMAIL::TEXT, '@', 2)::STUDITOPIA.CITEXT
    ORDER BY T.NAME, T.ID;
$$ LANGUAGE SQL;
