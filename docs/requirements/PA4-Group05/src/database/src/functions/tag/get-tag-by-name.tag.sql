DROP FUNCTION IF EXISTS STUDITOPIA.GET_TAG_BY_NAME(TEXT);
CREATE OR REPLACE FUNCTION STUDITOPIA.GET_TAG_BY_NAME(P_NAME TEXT)
RETURNS TABLE (ID INT, NAME TEXT, NUM_TAG INT, NUM_POST INT, ICON INT, DESCRIPTION TEXT, CATEGORY TEXT, CREATED_TIME TIMESTAMPTZ)
AS $$
    SELECT T.ID, T.NAME, T.NUM_TAG, T.NUM_POST, T.ICON, T.DESCRIPTION, CAT.NAME::TEXT, T.CREATED_TIME
    FROM STUDITOPIA.TAG T
    LEFT JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
    WHERE UPPER(T.NAME) = UPPER(P_NAME);
$$ LANGUAGE SQL;
