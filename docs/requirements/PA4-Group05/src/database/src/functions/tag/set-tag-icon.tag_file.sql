CREATE OR REPLACE FUNCTION STUDITOPIA.SET_TAG_ICON(P_TAG_ID INT, P_FILE_ID INT)
RETURNS BOOLEAN AS $$
BEGIN
    IF P_FILE_ID IS NOT NULL AND NOT EXISTS (
        SELECT 1
        FROM STUDITOPIA.FILE F
        WHERE F.ID = P_FILE_ID
    ) THEN
        RAISE EXCEPTION 'File % does not exist', P_FILE_ID USING ERRCODE = '23503';
    END IF;

    UPDATE STUDITOPIA.TAG
    SET ICON = P_FILE_ID
    WHERE ID = P_TAG_ID;

    RETURN FOUND;
END $$ LANGUAGE plpgsql;
