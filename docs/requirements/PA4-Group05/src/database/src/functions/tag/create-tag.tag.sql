DROP FUNCTION IF EXISTS STUDITOPIA.CREATE_TAG(TEXT, TEXT);

CREATE OR REPLACE FUNCTION STUDITOPIA.CREATE_TAG(P_NAME TEXT, P_CATEGORY TEXT, P_DESCRIPTION TEXT)
RETURNS INT AS $$
DECLARE
    V_CATEGORY_ID INT;
    V_TAG_ID INT;
BEGIN
    IF P_NAME IS NULL OR BTRIM(P_NAME) = '' THEN
        RAISE EXCEPTION 'Tag name is required' USING ERRCODE = '22023';
    END IF;

    SELECT ID INTO V_CATEGORY_ID
    FROM STUDITOPIA.CATEGORY
    WHERE NAME = P_CATEGORY::STUDITOPIA.CITEXT;

    IF V_CATEGORY_ID IS NULL THEN
        RAISE EXCEPTION 'Category % does not exist', P_CATEGORY USING ERRCODE = '23503';
    END IF;

    INSERT INTO STUDITOPIA.TAG(NAME, CATEGORY_ID, DESCRIPTION)
    VALUES (P_NAME, V_CATEGORY_ID, P_DESCRIPTION)
    RETURNING ID INTO V_TAG_ID;

    RETURN V_TAG_ID;
END $$ LANGUAGE plpgsql;