DROP FUNCTION IF EXISTS STUDITOPIA.GET_TAG(TEXT);
DROP FUNCTION IF EXISTS STUDITOPIA.GET_TAG();
CREATE OR REPLACE FUNCTION STUDITOPIA.GET_TAG(P_CATEGORY TEXT)
RETURNS TABLE (ID INT, NAME TEXT, NUM_TAG INT, NUM_POST INT, ICON INT, HOT FLOAT, DESCRIPTION TEXT)
AS $$
    SELECT T.ID, T.NAME, T.NUM_TAG, T.NUM_POST, T.ICON, T.HOT, T.DESCRIPTION
    FROM STUDITOPIA.TAG T
    JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
    WHERE CAT.NAME = P_CATEGORY::STUDITOPIA.CITEXT
    ORDER BY T.NAME, T.ID;
$$ LANGUAGE SQL;

CREATE OR REPLACE FUNCTION STUDITOPIA.GET_TAG()
RETURNS TABLE (ID INT, NAME TEXT, NUM_TAG INT, NUM_POST INT, ICON INT, HOT FLOAT, DESCRIPTION TEXT)
AS $$
    SELECT T.ID, T.NAME, T.NUM_TAG, T.NUM_POST, T.ICON, T.HOT, T.DESCRIPTION
    FROM STUDITOPIA.TAG T
    JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
    ORDER BY T.NAME, T.ID;
$$ LANGUAGE SQL;
