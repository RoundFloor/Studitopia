CREATE OR REPLACE FUNCTION STUDITOPIA.GET_RELEVANT_TAG(IDS INT[])
RETURNS TABLE (ID INT, NAME TEXT, NUM_POST INT) AS $$
BEGIN
    RETURN QUERY
    SELECT T.ID, T.NAME, COUNT(IPT.POST_ID)::INT
    FROM STUDITOPIA.TAG T
    JOIN STUDITOPIA.INCLUDE_POST_TAG IPT ON IPT.TAG_ID = T.ID
    JOIN (
        SELECT T2.POST_ID, ARRAY_AGG(T2.TAG_ID) AS ARR
        FROM STUDITOPIA.INCLUDE_POST_TAG T2
        GROUP BY T2.POST_ID
    ) T2 ON T2.POST_ID = IPT.POST_ID AND T2.ARR @> IDS
    GROUP BY T.ID, T.NAME;
END
$$ LANGUAGE plpgsql;
