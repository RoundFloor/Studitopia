DROP FUNCTION IF EXISTS STUDITOPIA.GET_TAGS_BY_ID(INT[]);
CREATE OR REPLACE FUNCTION STUDITOPIA.GET_TAGS_BY_ID(ARR INT[])
RETURNS TABLE (ID INT, NAME TEXT, CATEGORY TEXT)
AS $$
    SELECT T.ID, T.NAME, CAT.NAME
    FROM STUDITOPIA.TAG T
    JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
    WHERE T.ID = ANY(ARR);
$$ LANGUAGE SQL;
