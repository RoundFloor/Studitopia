CREATE OR REPLACE FUNCTION STUDITOPIA.GET_FILE_BY_ACCOUNT(P_ACCOUNT_ID INT)
RETURNS TABLE (ID INT, NAME TEXT, SRC TEXT, ACCOUNT_ID INT, UPDATED_TIME TIMESTAMPTZ, CREATED_TIME TIMESTAMPTZ)
AS $$
    SELECT F.ID, F.NAME, F.SRC, F.ACCOUNT_ID, F.UPDATED_TIME, F.CREATED_TIME
    FROM STUDITOPIA.FILE F
    WHERE F.ACCOUNT_ID = P_ACCOUNT_ID
    ORDER BY F.CREATED_TIME, F.ID;
$$ LANGUAGE SQL;
