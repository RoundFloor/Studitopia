DROP FUNCTION IF EXISTS STUDITOPIA.CREATE_FILE(TEXT, INT);

CREATE OR REPLACE FUNCTION STUDITOPIA.CREATE_FILE(P_NAME TEXT, P_ACCOUNT_ID INT)
RETURNS TABLE (ID INT, SRC TEXT) AS $$
BEGIN
    IF P_NAME IS NULL OR BTRIM(P_NAME) = '' THEN
        RAISE EXCEPTION 'File name is required' USING ERRCODE = '22023';
    END IF;

    RETURN QUERY
    INSERT INTO STUDITOPIA.FILE AS F (NAME, ACCOUNT_ID)
    VALUES (P_NAME, P_ACCOUNT_ID)
    RETURNING F.ID, F.SRC;
END $$ LANGUAGE plpgsql;
