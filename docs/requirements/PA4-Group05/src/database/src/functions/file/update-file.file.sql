DROP FUNCTION IF EXISTS STUDITOPIA.UPDATE_FILE(INT, INT, TEXT, TEXT);

CREATE OR REPLACE FUNCTION STUDITOPIA.UPDATE_FILE(P_FILE_ID INT, P_ACCOUNT_ID INT, P_NAME TEXT)
RETURNS BOOLEAN AS $$
BEGIN
    IF P_NAME IS NULL OR BTRIM(P_NAME) = '' THEN
        RAISE EXCEPTION 'File name is required' USING ERRCODE = '22023';
    END IF;

    UPDATE STUDITOPIA.FILE
    SET NAME = P_NAME, UPDATED_TIME = NOW()
    WHERE ID = P_FILE_ID AND ACCOUNT_ID = P_ACCOUNT_ID;

    RETURN FOUND;
END $$ LANGUAGE plpgsql;
