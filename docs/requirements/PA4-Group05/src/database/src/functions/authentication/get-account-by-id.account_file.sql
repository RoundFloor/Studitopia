DROP FUNCTION IF EXISTS STUDITOPIA.GET_ACCOUNT_BY_ID(INT);
DROP TYPE IF EXISTS STUDITOPIA.TYPE_TAG_NAME_ID;

CREATE OR REPLACE FUNCTION STUDITOPIA.GET_ACCOUNT_BY_ID(P_ACCOUNT_ID INT)
RETURNS TABLE (
    DISPLAYNAME VARCHAR(32),
    USERNAME STUDITOPIA.TYPE_USERNAME,
    UNIVERSITY_NAME TEXT,
    UNIVERSITY_ID INT,
    FACULTY_NAME TEXT,
    FACULTY_ID INT,
    MAJOR_NAME TEXT,
    MAJOR_ID INT,
    AVATAR INT,
    ROLE TEXT,
    STATUS TEXT,
    CREATE_TIME TIMESTAMPTZ
)
AS $$
    SELECT C.DISPLAYNAME,
        C.USERNAME,
        (SELECT T.NAME::TEXT
         FROM STUDITOPIA.RELATED_EMAIL_TAG RET
         JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
         JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
         WHERE RET.DOMAIN_ID = C.DOMAIN_ID AND CAT.NAME = 'UNIVERSITY'
         LIMIT 1),
        (SELECT T.ID
         FROM STUDITOPIA.RELATED_EMAIL_TAG RET
         JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
         JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
         WHERE RET.DOMAIN_ID = C.DOMAIN_ID AND CAT.NAME = 'UNIVERSITY'
         LIMIT 1),
        (SELECT T.NAME::TEXT
         FROM STUDITOPIA.RELATED_EMAIL_TAG RET
         JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
         JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
         WHERE RET.DOMAIN_ID = C.DOMAIN_ID AND CAT.NAME = 'FACULTY'
         LIMIT 1),
        (SELECT T.ID
         FROM STUDITOPIA.RELATED_EMAIL_TAG RET
         JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
         JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
         WHERE RET.DOMAIN_ID = C.DOMAIN_ID AND CAT.NAME = 'FACULTY'
         LIMIT 1),
        (SELECT T.NAME::TEXT
         FROM STUDITOPIA.RELATED_EMAIL_TAG RET
         JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
         JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
         WHERE RET.DOMAIN_ID = C.DOMAIN_ID AND CAT.NAME = 'MAJOR'
         LIMIT 1),
        (SELECT T.ID
         FROM STUDITOPIA.RELATED_EMAIL_TAG RET
         JOIN STUDITOPIA.TAG T ON T.ID = RET.TAG_ID
         JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = T.CATEGORY_ID
         WHERE RET.DOMAIN_ID = C.DOMAIN_ID AND CAT.NAME = 'MAJOR'
         LIMIT 1),
        C.AVATAR, C.ROLE, C.STATUS, C.CREATE_TIME
    FROM STUDITOPIA.ACCOUNT C
    WHERE C.ID = P_ACCOUNT_ID
$$ LANGUAGE SQL;
