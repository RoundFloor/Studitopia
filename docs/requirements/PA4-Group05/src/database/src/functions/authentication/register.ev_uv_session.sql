CREATE OR REPLACE FUNCTION STUDITOPIA.REGISTER(
    PDISPLAYNAME TEXT,
    PEMAIL TEXT,
    PUSERNAME TEXT,
    PPASSWORD TEXT
) RETURNS TABLE (USER_ID INT, SESSION_ID INT, ACCOUNT_ROLE TEXT, ACCOUNT_STATUS TEXT) AS
$$
DECLARE
    v_id INT;
BEGIN
    IF (PDISPLAYNAME IS NULL OR NOT (LENGTH(PDISPLAYNAME) BETWEEN 8 AND 32) OR NOT (PDISPLAYNAME ~ '^[a-zA-Z0-9]+([ ][a-zA-Z0-9]+)*$')) THEN
        RAISE EXCEPTION 'INVALID DISPLAY NAME' USING ERRCODE='45001';
    END IF;

    PERFORM STUDITOPIA.USERNAME_VALIDATION(PUSERNAME);
    PERFORM STUDITOPIA.EMAIL_VALIDATION(PEMAIL);

    RETURN QUERY
    INSERT INTO STUDITOPIA.ACCOUNT(DISPLAYNAME, EMAIL, USERNAME, PASSWORD, DOMAIN_ID)
    SELECT PDISPLAYNAME, PEMAIL, PUSERNAME, STUDITOPIA.CRYPT(PPASSWORD, STUDITOPIA.GEN_SALT('bf', 10)), D.ID
    FROM STUDITOPIA.DOMAIN D
    WHERE D.DOMAIN = SPLIT_PART(PEMAIL, '@', 2)::STUDITOPIA.CITEXT
    RETURNING ID, STUDITOPIA.REGISTER_SESSION(ID), ROLE, STATUS;
END $$ LANGUAGE plpgsql;

