CREATE OR REPLACE FUNCTION STUDITOPIA.USERNAME_VALIDATION(PUSERNAME TEXT) RETURNS BOOLEAN AS $$
BEGIN
    IF (PUSERNAME IS NULL OR NOT (PUSERNAME ~ '^[a-z][a-z0-9]*([.][a-z0-9]+)*$' AND LENGTH(PUSERNAME) BETWEEN 8 AND 32)) THEN
        RAISE EXCEPTION 'INVALID USERNAME NAME' USING ERRCODE='45003';
    END IF;

    IF (EXISTS (SELECT 1 FROM STUDITOPIA.ACCOUNT WHERE USERNAME = PUSERNAME::STUDITOPIA.CITEXT)) THEN
        RAISE EXCEPTION 'DUPPLICATE USERNAME' USING ERRCODE='47002';
    END IF;

    RETURN TRUE;
END $$ LANGUAGE plpgsql;
