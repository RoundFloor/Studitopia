CREATE OR REPLACE FUNCTION STUDITOPIA.SET_ACCOUNT_AVATAR(P_ACCOUNT_ID INT, P_FILE_ID INT)
RETURNS BOOLEAN AS $$
BEGIN
    IF P_FILE_ID IS NOT NULL AND NOT EXISTS (
        SELECT 1
        FROM STUDITOPIA.FILE F
        WHERE F.ID = P_FILE_ID AND F.ACCOUNT_ID = P_ACCOUNT_ID
    ) THEN
        RAISE EXCEPTION 'File % is not owned by account %', P_FILE_ID, P_ACCOUNT_ID
            USING ERRCODE = '23503';
    END IF;

    UPDATE STUDITOPIA.ACCOUNT
    SET AVATAR = P_FILE_ID
    WHERE ID = P_ACCOUNT_ID;

    RETURN FOUND;
END $$ LANGUAGE plpgsql;
