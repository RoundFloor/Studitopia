CREATE TABLE STUDITOPIA.VOTE(
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    COMMENT_ID INT NOT NULL REFERENCES STUDITOPIA.COMMENT(ID),
    ACCOUNT_ID INT NOT NULL REFERENCES STUDITOPIA.ACCOUNT(ID),
    TYPE INT NOT NULL DEFAULT 0 CHECK (TYPE BETWEEN 0 AND 1),
    TIME_CREATED TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IDX_VOTE_COMMENT_ACCOUNT ON STUDITOPIA.VOTE(COMMENT_ID, ACCOUNT_ID);
