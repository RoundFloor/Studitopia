CREATE TABLE STUDITOPIA.COMMENT(
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CONTENT TEXT NOT NULL,
    ACCOUNT_ID INT NOT NULL REFERENCES STUDITOPIA.ACCOUNT(ID),
    UPVOTE INT NOT NULL DEFAULT 0,
    DOWNVOTE INT NOT NULL DEFAULT 0,
    COMMENT INT NOT NULL DEFAULT 0,
    HOT FLOAT NOT NULL DEFAULT 0,
    COMMENT_ID INT REFERENCES STUDITOPIA.COMMENT(ID) CHECK (COMMENT_ID != ID) DEFAULT NULL,
    CREATED_TIME TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
