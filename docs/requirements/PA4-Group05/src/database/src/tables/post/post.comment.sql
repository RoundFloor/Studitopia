CREATE TABLE STUDITOPIA.POST(
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TITLE TEXT NOT NULL,
    ACCOUNT_ID INT NOT NULL REFERENCES STUDITOPIA.ACCOUNT(ID),
    COMMENT_ID INT NOT NULL REFERENCES STUDITOPIA.COMMENT(ID),
    TRUE_RESPONSE INT REFERENCES STUDITOPIA.COMMENT(ID) DEFAULT NULL,
    HOT FLOAT NOT NULL DEFAULT 0,
    CREATED_TIME TIMESTAMPTZ NOT NULL DEFAULT NOW()
);