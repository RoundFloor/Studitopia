CREATE TABLE STUDITOPIA.TAG(
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME TEXT,
    DESCRIPTION TEXT DEFAULT NULL,
    ICON INT DEFAULT NULL,
    NUM_TAG INT NOT NULL DEFAULT 0,
    NUM_POST INT NOT NULL DEFAULT 0,
    HOT FLOAT NOT NULL DEFAULT 0,
    CATEGORY_ID INT REFERENCES STUDITOPIA.CATEGORY(ID) DEFAULT NULL,
    CREATED_TIME TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX UK_TAG_NAME ON STUDITOPIA.TAG(UPPER(NAME));