CREATE TABLE STUDITOPIA.TAG_CONTAIN(
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TAG_ID_A INT NOT NULL REFERENCES STUDITOPIA.TAG(ID),
    TAG_ID_b INT NOT NULL REFERENCES STUDITOPIA.TAG(ID),
    CONSTRAINT CK_ID_DIFERENCE CHECK (TAG_ID_A != TAG_ID_B)
);
CREATE UNIQUE INDEX UK_ID_RELATION ON STUDITOPIA.TAG_CONTAIN(GREATEST(TAG_ID_A, TAG_ID_B), LEAST(TAG_ID_A, TAG_ID_B));