CREATE TABLE STUDITOPIA.FILE(
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME TEXT NOT NULL,
    ACCOUNT_ID INT NOT NULL REFERENCES STUDITOPIA.ACCOUNT(ID),
    SRC TEXT GENERATED ALWAYS AS (ACCOUNT_ID::TEXT || '/' || ID::TEXT) STORED UNIQUE,
    UPDATED_TIME TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CREATED_TIME TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IDX_FILE_ACCOUNT ON STUDITOPIA.FILE(ACCOUNT_ID);
