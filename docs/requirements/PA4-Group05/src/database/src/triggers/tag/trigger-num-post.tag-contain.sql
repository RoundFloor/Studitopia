CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_NUM_SUBTAG()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE STUDITOPIA.TAG
    SET NUM_TAG = NUM_TAG + 1
    WHERE ID = NEW.TAG_ID_A;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_NUM_SUBTAG()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.TAG_ID_A = NEW.TAG_ID_A THEN
        RETURN NEW;
    END IF;

    UPDATE STUDITOPIA.TAG
    SET NUM_TAG = NUM_TAG - 1
    WHERE ID = OLD.TAG_ID_A;

    UPDATE STUDITOPIA.TAG
    SET NUM_TAG = NUM_TAG + 1
    WHERE ID = NEW.TAG_ID_A;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_NUM_SUBTAG()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE STUDITOPIA.TAG
    SET NUM_TAG = NUM_TAG - 1
    WHERE ID = OLD.TAG_ID_A;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS TRIGGER_INSERT_NUM_SUB_TAG ON STUDITOPIA.TAG_CONTAIN;
CREATE TRIGGER TRIGGER_INSERT_NUM_SUB_TAG
AFTER INSERT ON STUDITOPIA.TAG_CONTAIN
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_NUM_SUBTAG();

DROP TRIGGER IF EXISTS UPDATE_UPDATE_NUM_SUB_TAG ON STUDITOPIA.TAG_CONTAIN;
CREATE TRIGGER UPDATE_UPDATE_NUM_SUB_TAG
AFTER UPDATE ON STUDITOPIA.TAG_CONTAIN
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_NUM_SUBTAG();

DROP TRIGGER IF EXISTS DELETE_UPDATE_NUM_SUB_TAG ON STUDITOPIA.TAG_CONTAIN;
CREATE TRIGGER DELETE_UPDATE_NUM_SUB_TAG
AFTER DELETE ON STUDITOPIA.TAG_CONTAIN
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_NUM_SUBTAG();
