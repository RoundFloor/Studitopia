CREATE OR REPLACE FUNCTION STUDITOPIA.FN_ENFORCE_ONE_EMAIL_CATEGORY()
RETURNS TRIGGER AS $$
DECLARE
    V_CATEGORY TEXT;
BEGIN
    SELECT CAT.NAME::TEXT
    INTO V_CATEGORY
    FROM STUDITOPIA.TAG TG
    JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = TG.CATEGORY_ID
    WHERE TG.ID = NEW.TAG_ID;

    IF V_CATEGORY IN ('UNIVERSITY', 'FACULTY', 'MAJOR') AND EXISTS (
        SELECT 1
        FROM STUDITOPIA.RELATED_EMAIL_TAG RET
        JOIN STUDITOPIA.TAG TG ON TG.ID = RET.TAG_ID
        JOIN STUDITOPIA.CATEGORY CAT ON CAT.ID = TG.CATEGORY_ID
        WHERE RET.DOMAIN_ID = NEW.DOMAIN_ID
          AND RET.ID IS DISTINCT FROM NEW.ID
          AND RET.TAG_ID <> NEW.TAG_ID
          AND CAT.NAME::TEXT = V_CATEGORY
    ) THEN
        RAISE EXCEPTION 'Only one % tag is allowed per email domain', V_CATEGORY
            USING ERRCODE = '23505';
    END IF;

    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_ENFORCE_ONE_EMAIL_CATEGORY_ON_TAG()
RETURNS TRIGGER AS $$
DECLARE
    V_CATEGORY TEXT;
BEGIN
    SELECT CAT.NAME::TEXT
    INTO V_CATEGORY
    FROM STUDITOPIA.CATEGORY CAT
    WHERE CAT.ID = NEW.CATEGORY_ID;

    IF V_CATEGORY IN ('UNIVERSITY', 'FACULTY', 'MAJOR') AND EXISTS (
        SELECT 1
        FROM STUDITOPIA.RELATED_EMAIL_TAG CUR
        WHERE CUR.TAG_ID = NEW.ID
          AND EXISTS (
              SELECT 1
              FROM STUDITOPIA.RELATED_EMAIL_TAG OTHER_RET
              JOIN STUDITOPIA.TAG OTHER_TG ON OTHER_TG.ID = OTHER_RET.TAG_ID
              JOIN STUDITOPIA.CATEGORY OTHER_CAT ON OTHER_CAT.ID = OTHER_TG.CATEGORY_ID
              WHERE OTHER_RET.DOMAIN_ID = CUR.DOMAIN_ID
                AND OTHER_RET.TAG_ID <> NEW.ID
                AND OTHER_CAT.NAME::TEXT = V_CATEGORY
          )
    ) THEN
        RAISE EXCEPTION 'Only one % tag is allowed per email domain', V_CATEGORY
            USING ERRCODE = '23505';
    END IF;

    RETURN NEW;
END
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS TRIGGER_ENFORCE_ONE_EMAIL_CATEGORY ON STUDITOPIA.RELATED_EMAIL_TAG;
CREATE TRIGGER TRIGGER_ENFORCE_ONE_EMAIL_CATEGORY
BEFORE INSERT OR UPDATE OF TAG_ID, DOMAIN_ID ON STUDITOPIA.RELATED_EMAIL_TAG
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_ENFORCE_ONE_EMAIL_CATEGORY();

DROP TRIGGER IF EXISTS TRIGGER_ENFORCE_ONE_EMAIL_CATEGORY_ON_TAG ON STUDITOPIA.TAG;
CREATE TRIGGER TRIGGER_ENFORCE_ONE_EMAIL_CATEGORY_ON_TAG
BEFORE UPDATE OF CATEGORY_ID ON STUDITOPIA.TAG
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_ENFORCE_ONE_EMAIL_CATEGORY_ON_TAG();
