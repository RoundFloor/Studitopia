CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_NUM_POST()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE STUDITOPIA.TAG
    SET NUM_POST = NUM_POST + 1
    WHERE ID = NEW.TAG_ID;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_NUM_POST()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.TAG_ID = NEW.TAG_ID THEN
        RETURN NEW;
    END IF;

    UPDATE STUDITOPIA.TAG
    SET NUM_POST = NUM_POST - 1
    WHERE ID = OLD.TAG_ID;

    UPDATE STUDITOPIA.TAG
    SET NUM_POST = NUM_POST + 1
    WHERE ID = NEW.TAG_ID;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_NUM_POST()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE STUDITOPIA.TAG
    SET NUM_POST = NUM_POST - 1
    WHERE ID = OLD.TAG_ID;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS TRIGGER_INSERT_NUM_POST ON STUDITOPIA.INCLUDE_POST_TAG;
CREATE TRIGGER TRIGGER_INSERT_NUM_POST
AFTER INSERT ON STUDITOPIA.INCLUDE_POST_TAG
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_NUM_POST();

DROP TRIGGER IF EXISTS UPDATE_UPDATE_NUM_POST ON STUDITOPIA.INCLUDE_POST_TAG;
CREATE TRIGGER UPDATE_UPDATE_NUM_POST
AFTER UPDATE ON STUDITOPIA.INCLUDE_POST_TAG
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_NUM_POST();

DROP TRIGGER IF EXISTS DELETE_UPDATE_NUM_POST ON STUDITOPIA.INCLUDE_POST_TAG;
CREATE TRIGGER DELETE_UPDATE_NUM_POST
AFTER DELETE ON STUDITOPIA.INCLUDE_POST_TAG
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_NUM_POST();
