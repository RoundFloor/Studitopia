CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_VOTE() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.TYPE = 0 THEN
        UPDATE STUDITOPIA.COMMENT
        SET UPVOTE = UPVOTE + 1
        WHERE ID = NEW.COMMENT_ID;
    ELSE
        UPDATE STUDITOPIA.COMMENT
        SET DOWNVOTE = DOWNVOTE + 1
        WHERE ID = NEW.COMMENT_ID;
    END IF;
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_VOTE() RETURNS TRIGGER AS $$
BEGIN
    IF OLD.TYPE = 0 THEN
        UPDATE STUDITOPIA.COMMENT
        SET UPVOTE = UPVOTE - 1
        WHERE ID = OLD.COMMENT_ID;
    ELSE
        UPDATE STUDITOPIA.COMMENT
        SET DOWNVOTE = DOWNVOTE - 1
        WHERE ID = OLD.COMMENT_ID;
    END IF;

    IF NEW.TYPE = 0 THEN
        UPDATE STUDITOPIA.COMMENT
        SET UPVOTE = UPVOTE + 1
        WHERE ID = NEW.COMMENT_ID;
    ELSE
        UPDATE STUDITOPIA.COMMENT
        SET DOWNVOTE = DOWNVOTE + 1
        WHERE ID = NEW.COMMENT_ID;
    END IF;

    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_VOTE() RETURNS TRIGGER AS $$
BEGIN
    IF OLD.TYPE = 0 THEN
        UPDATE STUDITOPIA.COMMENT
        SET UPVOTE = UPVOTE - 1
        WHERE ID = OLD.COMMENT_ID;
    ELSE
        UPDATE STUDITOPIA.COMMENT
        SET DOWNVOTE = DOWNVOTE - 1
        WHERE ID = OLD.COMMENT_ID;
    END IF;

    RETURN OLD;
END
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS TRIGGER_INSERT_VOTE ON STUDITOPIA.VOTE;
CREATE TRIGGER TRIGGER_INSERT_VOTE
AFTER INSERT ON STUDITOPIA.VOTE
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_VOTE();

DROP TRIGGER IF EXISTS TRIGGER_UPDATE_VOTE ON STUDITOPIA.VOTE;
CREATE TRIGGER TRIGGER_UPDATE_VOTE
AFTER UPDATE ON STUDITOPIA.VOTE
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_VOTE();

DROP TRIGGER IF EXISTS TRIGGER_DELETE_VOTE ON STUDITOPIA.VOTE;
CREATE TRIGGER TRIGGER_DELETE_VOTE
AFTER DELETE ON STUDITOPIA.VOTE
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_VOTE();
