CREATE OR REPLACE FUNCTION STUDITOPIA.FN_RECALC_TAG_HOT(P_TAG_ID INT)
RETURNS VOID AS $$
BEGIN
    UPDATE STUDITOPIA.TAG T
    SET HOT = COALESCE((
        SELECT AVG(P.HOT)
        FROM STUDITOPIA.INCLUDE_POST_TAG IPT
        JOIN STUDITOPIA.POST P ON P.ID = IPT.POST_ID
        WHERE IPT.TAG_ID = T.ID
    ), 0)
    WHERE T.ID = P_TAG_ID;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_RECALC_COMMENT_HOT(P_COMMENT_ID INT)
RETURNS VOID AS $$
DECLARE
    V_HOT FLOAT;
BEGIN
    SELECT C.UPVOTE + C.DOWNVOTE + C.COMMENT * 2
           + COALESCE((
                 SELECT AVG(CHILD.HOT)
                 FROM STUDITOPIA.COMMENT CHILD
                 WHERE CHILD.COMMENT_ID = C.ID
             ), 0)
    INTO V_HOT
    FROM STUDITOPIA.COMMENT C
    WHERE C.ID = P_COMMENT_ID;

    IF V_HOT IS NULL THEN
        RETURN;
    END IF;

    UPDATE STUDITOPIA.COMMENT
    SET HOT = V_HOT
    WHERE ID = P_COMMENT_ID;

    UPDATE STUDITOPIA.POST
    SET HOT = V_HOT
    WHERE COMMENT_ID = P_COMMENT_ID;

    UPDATE STUDITOPIA.TAG T
    SET HOT = COALESCE((
        SELECT AVG(P.HOT)
        FROM STUDITOPIA.INCLUDE_POST_TAG IPT
        JOIN STUDITOPIA.POST P ON P.ID = IPT.POST_ID
        WHERE IPT.TAG_ID = T.ID
    ), 0)
    WHERE T.ID IN (
        SELECT IPT.TAG_ID
        FROM STUDITOPIA.INCLUDE_POST_TAG IPT
        JOIN STUDITOPIA.POST P ON P.ID = IPT.POST_ID
        WHERE P.COMMENT_ID = P_COMMENT_ID
    );
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_RECALC_COMMENT_HOT_TREE(P_IDS INT[])
RETURNS VOID AS $$
DECLARE
    V_ID INT;
BEGIN
    FOR V_ID IN
        WITH RECURSIVE TREE AS (
            SELECT C.ID, C.COMMENT_ID, 0 AS DEPTH
            FROM STUDITOPIA.COMMENT C
            WHERE C.ID IN (SELECT DISTINCT UNNEST(P_IDS))
            UNION ALL
            SELECT PARENT.ID, PARENT.COMMENT_ID, TREE.DEPTH + 1
            FROM STUDITOPIA.COMMENT PARENT
            JOIN TREE ON PARENT.ID = TREE.COMMENT_ID
        ), RANKED AS (
            SELECT DISTINCT ON (ID) ID, DEPTH
            FROM TREE
            ORDER BY ID, DEPTH DESC
        )
        SELECT ID
        FROM RANKED
        ORDER BY DEPTH ASC
    LOOP
        PERFORM STUDITOPIA.FN_RECALC_COMMENT_HOT(V_ID);
    END LOOP;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_HOT_INSERT_COMMENT()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM STUDITOPIA.FN_RECALC_COMMENT_HOT_TREE(
        ARRAY_REMOVE(ARRAY[NEW.ID, NEW.COMMENT_ID], NULL)
    );
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_HOT_UPDATE_COMMENT()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.UPVOTE IS NOT DISTINCT FROM NEW.UPVOTE
       AND OLD.DOWNVOTE IS NOT DISTINCT FROM NEW.DOWNVOTE
       AND OLD.COMMENT IS NOT DISTINCT FROM NEW.COMMENT
       AND OLD.COMMENT_ID IS NOT DISTINCT FROM NEW.COMMENT_ID THEN
        RETURN NEW;
    END IF;

    PERFORM STUDITOPIA.FN_RECALC_COMMENT_HOT_TREE(
        ARRAY_REMOVE(ARRAY[OLD.ID, NEW.ID, OLD.COMMENT_ID, NEW.COMMENT_ID], NULL)
    );
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_HOT_DELETE_COMMENT()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM STUDITOPIA.FN_RECALC_COMMENT_HOT_TREE(
        ARRAY_REMOVE(ARRAY[OLD.COMMENT_ID], NULL)
    );
    RETURN OLD;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_HOT_POST()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' OR OLD.COMMENT_ID IS DISTINCT FROM NEW.COMMENT_ID THEN
        PERFORM STUDITOPIA.FN_RECALC_COMMENT_HOT_TREE(
            ARRAY_REMOVE(ARRAY[NEW.COMMENT_ID], NULL)
        );
    END IF;
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_HOT_POST_TAG()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM STUDITOPIA.FN_RECALC_TAG_HOT(OLD.TAG_ID);
        RETURN OLD;
    END IF;

    IF TG_OP = 'INSERT' THEN
        PERFORM STUDITOPIA.FN_RECALC_TAG_HOT(NEW.TAG_ID);
        RETURN NEW;
    END IF;

    IF OLD.TAG_ID IS DISTINCT FROM NEW.TAG_ID THEN
        PERFORM STUDITOPIA.FN_RECALC_TAG_HOT(OLD.TAG_ID);
        PERFORM STUDITOPIA.FN_RECALC_TAG_HOT(NEW.TAG_ID);
    END IF;
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

