FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_HOT_POST_TAG();

DO $$
DECLARE
    V_ID INT;
BEGIN
    FOR V_ID IN
        WITH RECURSIVE TREE AS (
            SELECT ID, COMMENT_ID, 0 AS DEPTH
            FROM STUDITOPIA.COMMENT
            WHERE COMMENT_ID IS NULL
            UNION ALL
            SELECT C.ID, C.COMMENT_ID, TREE.DEPTH + 1
            FROM STUDITOPIA.COMMENT C
            JOIN TREE ON C.COMMENT_ID = TREE.ID
        )
        SELECT ID
        FROM TREE
        ORDER BY DEPTH DESC
    LOOP
        PERFORM STUDITOPIA.FN_RECALC_COMMENT_HOT(V_ID);
    END LOOP;

    UPDATE STUDITOPIA.TAG T
    SET HOT = COALESCE((
        SELECT AVG(P.HOT)
        FROM STUDITOPIA.INCLUDE_POST_TAG IPT
        JOIN STUDITOPIA.POST P ON P.ID = IPT.POST_ID
        WHERE IPT.TAG_ID = T.ID
    ), 0);
END
$$;
