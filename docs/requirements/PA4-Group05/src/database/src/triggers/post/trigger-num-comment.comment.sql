CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_COMMENT_COUNT()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.COMMENT_ID IS NOT NULL THEN
        UPDATE STUDITOPIA.COMMENT
        SET COMMENT = COMMENT + 1
        WHERE ID = NEW.COMMENT_ID;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_COMMENT_COUNT()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.COMMENT_ID IS DISTINCT FROM NEW.COMMENT_ID THEN
        IF OLD.COMMENT_ID IS NOT NULL THEN
            UPDATE STUDITOPIA.COMMENT
            SET COMMENT = COMMENT - 1 - OLD.COMMENT
            WHERE ID = OLD.COMMENT_ID;
        END IF;

        IF NEW.COMMENT_ID IS NOT NULL THEN
            UPDATE STUDITOPIA.COMMENT
            SET COMMENT = COMMENT + 1 + NEW.COMMENT
            WHERE ID = NEW.COMMENT_ID;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_COMMENT_COUNT()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.COMMENT_ID IS NOT NULL THEN
        UPDATE STUDITOPIA.COMMENT
        SET COMMENT = COMMENT - 1 - OLD.COMMENT
        WHERE ID = OLD.COMMENT_ID;
    END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS TRIGGER_INSERT_COMMENT_COUNT ON STUDITOPIA.COMMENT;
CREATE TRIGGER TRIGGER_INSERT_COMMENT_COUNT
AFTER INSERT ON STUDITOPIA.COMMENT
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_INSERT_COMMENT_COUNT();

DROP TRIGGER IF EXISTS TRIGGER_UPDATE_COMMENT_COUNT ON STUDITOPIA.COMMENT;
CREATE TRIGGER TRIGGER_UPDATE_COMMENT_COUNT
AFTER UPDATE ON STUDITOPIA.COMMENT
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_UPDATE_COMMENT_COUNT();

DROP TRIGGER IF EXISTS TRIGGER_DELETE_COMMENT_COUNT ON STUDITOPIA.COMMENT;
CREATE TRIGGER TRIGGER_DELETE_COMMENT_COUNT
AFTER DELETE ON STUDITOPIA.COMMENT
FOR EACH ROW
EXECUTE FUNCTION STUDITOPIA.FN_TRIGGER_DELETE_COMMENT_COUNT();
