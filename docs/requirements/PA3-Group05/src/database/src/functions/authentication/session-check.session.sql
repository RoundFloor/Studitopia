CREATE OR REPLACE FUNCTION STUDITOPIA.SESSION_CHECK(SESSION_ID INT, USER_ID INT) RETURNS BOOLEAN AS
$$
BEGIN
    PERFORM *
    FROM STUDITOPIA.SESSION
    WHERE ID = SESSION_ID
      AND OWNER_ID = USER_ID
      AND STATUS = 'ACTIVE'
      AND EXPIRED_TIME > NOW();

    IF NOT FOUND THEN
        RAISE EXCEPTION 'INVALID SESSION' USING ERRCODE = '45005';
    END IF;

    RETURN TRUE;
END;
$$ LANGUAGE plpgsql;
