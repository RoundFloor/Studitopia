CREATE OR REPLACE FUNCTION STUDITOPIA.LOGOUT(PSESSION_ID INT, PUSER_ID INT) RETURNS BOOLEAN AS $$
BEGIN
    PERFORM STUDITOPIA.SESSION_CHECK(PSESSION_ID, PUSER_ID);

    UPDATE STUDITOPIA.SESSION
    SET STATUS = 'INACTIVE', EXPIRED_TIME = NOW()
    WHERE ID = PSESSION_ID AND OWNER_ID = PUSER_ID AND STATUS = 'ACTIVE';

    RETURN FOUND;
END $$ LANGUAGE plpgsql;
