CREATE OR REPLACE FUNCTION STUDITOPIA.LOGIN_BY_USERNAME(PUSERNAME TEXT, PPASSWORD TEXT)
RETURNS TABLE (SESSION_ID INT, USER_ID INT, ROLE TEXT, STATUS TEXT) AS $$
BEGIN
    RETURN QUERY
    SELECT STUDITOPIA.REGISTER_SESSION(C.ID), C.ID, C.ROLE, C.STATUS
    FROM STUDITOPIA.ACCOUNT C
    WHERE C.USERNAME = PUSERNAME::STUDITOPIA.CITEXT
      AND C.PASSWORD = STUDITOPIA.CRYPT(PPASSWORD, C.PASSWORD);

    IF NOT FOUND THEN
        RAISE EXCEPTION 'INVALID CREDENTIALS' USING ERRCODE='45007';
    END IF;
END $$ LANGUAGE plpgsql;

