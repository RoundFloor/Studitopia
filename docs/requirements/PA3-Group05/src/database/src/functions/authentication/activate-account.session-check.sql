CREATE OR REPLACE FUNCTION STUDITOPIA.ACTIVE_ACCOUNT(SESSION_ID INT, USER_ID INT) RETURNS BOOLEAN AS
$$
BEGIN
    PERFORM STUDITOPIA.SESSION_CHECK(SESSION_ID, USER_ID);

    UPDATE STUDITOPIA.ACCOUNT
    SET STATUS = 'ACTIVE', OTP = NULL
    WHERE ID = USER_ID AND STATUS IN ('INACTIVE', 'PREINIT');

    RETURN FOUND;
END
$$ LANGUAGE plpgsql;
