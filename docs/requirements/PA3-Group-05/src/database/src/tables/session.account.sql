CREATE TABLE STUDITOPIA.SESSION (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OWNER_ID INT NOT NULL REFERENCES STUDITOPIA.ACCOUNT(ID),
    CREATE_TIME TIMESTAMPTZ DEFAULT NOW(),
    EXPIRED_TIME TIMESTAMPTZ DEFAULT NOW() + INTERVAL '30d',
    STATUS TEXT DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE UNIQUE INDEX IDX_SESSION_OWNER ON STUDITOPIA.SESSION(ID, OWNER_ID) WHERE STATUS = 'ACTIVE';

CREATE OR REPLACE FUNCTION STUDITOPIA.REGISTER_SESSION(ACCOUNT_ID INT) RETURNS INT
AS $$
    INSERT INTO STUDITOPIA.SESSION(OWNER_ID) VALUES (ACCOUNT_ID)
    RETURNING ID;
$$ LANGUAGE SQL;
