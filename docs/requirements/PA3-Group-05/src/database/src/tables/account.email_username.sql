CREATE TABLE STUDITOPIA.ACCOUNT (
    ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    DISPLAYNAME VARCHAR(32),
    EMAIL STUDITOPIA.TYPE_EMAIL NOT NULL,
    USERNAME STUDITOPIA.TYPE_USERNAME NOT NULL,
    PASSWORD VARCHAR(60) NOT NULL,
    CREATE_TIME TIMESTAMPTZ DEFAULT NOW(),
    OTP INT DEFAULT NULL,
    ROLE TEXT NOT NULL DEFAULT 'STUDENT',
    STATUS TEXT NOT NULL DEFAULT 'INACTIVE',

    CONSTRAINT CK_ACCOUNT_STATUS CHECK (STATUS IN ('INACTIVE', 'PREINIT', 'ACTIVE', 'SUSPEND')),
    CONSTRAINT CK_ACCOUNT_ROLE CHECK (ROLE IN ('STUDENT', 'STAFF', 'ADMIN'))
);

CREATE UNIQUE INDEX IDX_UNIQUE_EMAIL ON STUDITOPIA.ACCOUNT(EMAIL);
CREATE UNIQUE INDEX IDX_UNIQUE_USERNAME ON STUDITOPIA.ACCOUNT(USERNAME);
